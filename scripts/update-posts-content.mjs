async function updatePosts() {
  console.log('Starting content update...');
  
  for (const [slug, content] of Object.entries(postsContent)) {
    try {
      // Query to find the post by slug
      const query = `*[_type == "post" && slug.current == $slug][0]`;
      const post = await client.fetch(query, { slug });
      
      if (!post) {
        console.log(`❌ Post not found: ${slug}`);
        continue;
      }
      
      // Convert markdown content to Portable Text blocks
      const contentBlocks = content.split('\n\n').map(paragraph => ({
        _type: 'block',
        _key: Math.random().toString(36).substr(2, 9),
        style: paragraph.startsWith('##') ? 'h2' : 'normal',
        children: [
          {
            _type: 'span',
            text: paragraph.replace(/^##\s*/, ''),
            marks: []
          }
        ]
      }));
      
      // Update the post with full content
      await client
        .patch(post._id)
        .set({ content: contentBlocks })
        .commit();
      
      console.log(`✅ Updated: ${slug}`);
    } catch (error) {
      console.error(`❌ Error updating ${slug}:`, error.message);
    }
  }
  
  console.log('Content update complete!');
}

